// Generates .design-sync/shims/default-exports.ts — a barrel that re-exports
// every DEFAULT-exported component under src/components as a named export.
//
// WHY THIS EXISTS
// The converter has no dist/ to bundle here, so it synthesizes an entry made of
// `export * from "<file>"` lines. `export *` deliberately does not re-export a
// module's default binding, so all 35 default-exported components — Header,
// HeroSection, FAQSection, MainLayout, the whole auth and dashboard set — were
// discovered as components, given cards, and then resolved to `undefined` on
// window.BuyAuto. Every one of those cards rendered blank.
//
// This barrel is wired in through cfg.extraEntries, whose exports are merged
// onto the global alongside the main entry.
//
// It is GENERATED rather than hand-written so it cannot rot: a component added
// with `export default` tomorrow is picked up by re-running the build command.
// Regenerate via cfg.buildCmd, which runs this before package-build.mjs.

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';

const SRC = 'src/components';
const OUT = '.design-sync/shims/default-exports.ts';

// Out of sync scope (mirrors the cfg.componentSrcMap exclusions): internal
// admin tooling and the non-visual analytics/SEO wrappers.
const SKIP_DIRS = new Set(['admin', 'analytics']);
const SKIP_FILES = new Set(['SEO.tsx']);

// `Toaster` is exported by BOTH ui/sonner.tsx and ui/toaster.tsx — the repo
// runs two toast systems side by side, and _app.tsx really does mount both.
// Two modules exporting the same name makes it ambiguous, and an ambiguous
// name is dropped from the namespace entirely, so `Toaster` reached the bundle
// as undefined.
//
// Re-exporting it from here under the plain name does NOT fix that: this barrel
// and the main entry are both `export * from` sources in the generated bundle
// entry, so the name stays ambiguous between the two and is dropped again.
// (Verified: `hasOwnProperty(window.BuyAuto, 'Toaster')` was false.)
//
// So both are exposed under UNAMBIGUOUS names instead. The plain `Toaster`
// card is excluded via cfg.componentSrcMap; conventions.md tells the design
// agent which one to reach for.
const AMBIGUOUS = [
  { name: 'SonnerToaster', from: 'src/components/ui/sonner.tsx', exported: 'Toaster' },
  { name: 'RadixToaster', from: 'src/components/ui/toaster.tsx', exported: 'Toaster' },
];

function walk(dir, acc = []) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) {
      if (!SKIP_DIRS.has(e.name)) walk(join(dir, e.name), acc);
    } else if (/\.(tsx|jsx)$/.test(e.name) && !SKIP_FILES.has(e.name)) {
      acc.push(join(dir, e.name));
    }
  }
  return acc;
}

// `export default function Foo`, `export default class Foo`, and the
// declare-then-`export default Foo;` form all name the component; an anonymous
// default (`export default () => …`) has no name to bind and is skipped.
const DEFAULT_RX = /export\s+default\s+(?:function|class)\s+([A-Z][A-Za-z0-9]*)/;
const DEFAULT_REF_RX = /export\s+default\s+([A-Z][A-Za-z0-9]*)\s*;/;

const found = [];
for (const file of walk(SRC).sort()) {
  const text = readFileSync(file, 'utf8');
  const name = DEFAULT_RX.exec(text)?.[1] ?? DEFAULT_REF_RX.exec(text)?.[1];
  if (name) found.push({ name, file });
}

// A default-exported name that is ALSO a named export somewhere would collide.
const seen = new Map();
const lines = [];
for (const { name, file } of found) {
  if (seen.has(name)) {
    console.error(`  ! duplicate default export ${name}: ${seen.get(name)} and ${file} — keeping the first`);
    continue;
  }
  seen.set(name, file);
  // Imported through the "@/" alias so it resolves identically to the way the
  // app's own code imports it.
  const spec = '@/' + relative('src', file).replace(/\.(tsx|jsx)$/, '').split('\\').join('/');
  lines.push(`export { default as ${name} } from ${JSON.stringify(spec)};`);
}

for (const { name, from, exported } of AMBIGUOUS) {
  const spec = '@/' + relative('src', from).replace(/\.(tsx|jsx)$/, '').split('\\').join('/');
  lines.push(`export { ${exported} as ${name} } from ${JSON.stringify(spec)};`);
}

writeFileSync(
  OUT,
  `// GENERATED by .design-sync/gen-default-exports.mjs — do not hand-edit.\n` +
    `// Re-exports default-exported components (which \`export *\` drops) plus the\n` +
    `// ambiguous Toaster pair, so they reach window.BuyAuto. See the generator\n` +
    `// for the full rationale.\n\n` +
    lines.join('\n') +
    '\n',
);

console.error(`  default-exports barrel: ${lines.length} export(s) → ${OUT}`);
